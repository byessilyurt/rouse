package app.rouse.alarm;

import android.content.ContentResolver;
import android.content.Context;
import android.database.Cursor;
import android.media.MediaPlayer;
import android.net.Uri;
import android.provider.OpenableColumns;
import android.webkit.MimeTypeMap;
import app.rouse.alarm.store.NativePrefs;
import app.rouse.alarm.store.SoundStore;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;
import java.util.UUID;
import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

/**
 * Bundled tones (res/raw/rouse_&lt;id&gt;.wav, generated by scripts/gen-sounds.ts) and user-picked
 * custom sounds, which are COPIED into device-protected storage (D-022) so they play before first
 * unlock and survive the original being deleted.
 */
public final class SoundLibrary {

    /** What the player should open: a raw resource or a file. */
    public static final class Source {
        public final int rawRes;
        public final File file;

        Source(int rawRes, File file) {
            this.rawRes = rawRes;
            this.file = file;
        }
    }

    private static final class TooLargeException extends IOException {
        private static final long serialVersionUID = 1L;

        TooLargeException() {
            super("too large");
        }
    }

    private final Context appContext;
    private final Context deviceContext;
    private final SoundStore store;

    public SoundLibrary(Context context) {
        this.appContext = context.getApplicationContext() != null ? context.getApplicationContext() : context;
        this.deviceContext = NativePrefs.deviceContext(context);
        this.store = new SoundStore(NativePrefs.get(context));
    }

    /** R.raw id for a bundled sound id; the backup tone for unknown ids. */
    public static int rawResFor(String id) {
        if (id == null) return R.raw.rouse_classic;
        switch (id) {
            case "pulse":
                return R.raw.rouse_pulse;
            case "siren":
                return R.raw.rouse_siren;
            case "chime":
                return R.raw.rouse_chime;
            case "buzzer":
                return R.raw.rouse_buzzer;
            case "rise":
                return R.raw.rouse_rise;
            case "classic":
            default:
                return R.raw.rouse_classic;
        }
    }

    public static Source backup() {
        return new Source(rawResFor(RouseConstants.BACKUP_SOUND_ID), null);
    }

    private File soundsDir() {
        File dir = new File(deviceContext.getFilesDir(), "sounds");
        if (!dir.exists() && !dir.mkdirs()) DiagLog.w("sound", "cannot create sounds dir");
        return dir;
    }

    /** Resolve a SoundRef; null if a custom sound is missing (caller plays the backup tone). */
    public Source resolve(String kind, String id) {
        if ("custom".equals(kind)) {
            JSONObject entry = store.find(id);
            if (entry == null) return null;
            File f = new File(soundsDir(), entry.optString("file", ""));
            return f.isFile() ? new Source(0, f) : null;
        }
        return new Source(rawResFor(id), null);
    }

    /** Bundled (BUNDLED_SOUNDS order) then custom (newest first), as SoundInfo JSON. */
    public JSONArray list() {
        JSONArray out = new JSONArray();
        try {
            for (int i = 0; i < RouseConstants.BUNDLED_SOUND_IDS.length; i++) {
                JSONObject ref = new JSONObject();
                ref.put("kind", "bundled");
                ref.put("id", RouseConstants.BUNDLED_SOUND_IDS[i]);
                JSONObject info = new JSONObject();
                info.put("ref", ref);
                info.put("name", RouseConstants.BUNDLED_SOUND_NAMES[i]);
                info.put("durationMs", RouseConstants.BUNDLED_SOUND_LOOP_MS[i]);
                out.put(info);
            }
            JSONArray custom = store.list();
            List<JSONObject> items = new ArrayList<>();
            for (int i = 0; i < custom.length(); i++) {
                JSONObject o = custom.optJSONObject(i);
                if (o != null) items.add(o);
            }
            Collections.sort(items, (a, b) -> Long.compare(b.optLong("addedAt", 0L), a.optLong("addedAt", 0L)));
            for (JSONObject o : items) out.put(customInfo(o));
        } catch (JSONException e) {
            DiagLog.e("sound", "list failed", e);
        }
        return out;
    }

    static JSONObject customInfo(JSONObject entry) throws JSONException {
        JSONObject ref = new JSONObject();
        ref.put("kind", "custom");
        ref.put("id", entry.optString("id"));
        ref.put("name", entry.optString("name"));
        JSONObject info = new JSONObject();
        info.put("ref", ref);
        info.put("name", entry.optString("name"));
        long d = entry.optLong("durationMs", -1L);
        info.put("durationMs", d > 0 ? (Object) d : JSONObject.NULL);
        return info;
    }

    /** Copy a picked document into storage and verify it decodes. Returns SoundInfo JSON. */
    public JSONObject importCustom(Uri uri) throws RouseError {
        ContentResolver cr = appContext.getContentResolver();
        String displayName = null;
        long size = -1L;
        try (Cursor c = cr.query(uri, new String[] { OpenableColumns.DISPLAY_NAME, OpenableColumns.SIZE }, null, null, null)) {
            if (c != null && c.moveToFirst()) {
                int ni = c.getColumnIndex(OpenableColumns.DISPLAY_NAME);
                if (ni >= 0 && !c.isNull(ni)) displayName = c.getString(ni);
                int si = c.getColumnIndex(OpenableColumns.SIZE);
                if (si >= 0 && !c.isNull(si)) size = c.getLong(si);
            }
        } catch (RuntimeException e) {
            DiagLog.w("sound", "metadata query failed: " + e.getClass().getSimpleName());
        }
        if (size > RouseConstants.MAX_CUSTOM_SOUND_BYTES) {
            throw new RouseError(RouseError.IO_ERROR, "The file is larger than 20 MB.");
        }

        String ext = extensionFor(displayName, cr.getType(uri));
        String id = UUID.randomUUID().toString();
        File out = new File(soundsDir(), id + "." + ext);
        long total = 0;
        try (InputStream in = cr.openInputStream(uri); OutputStream os = new FileOutputStream(out)) {
            if (in == null) throw new IOException("no stream");
            byte[] buf = new byte[64 * 1024];
            int n;
            while ((n = in.read(buf)) > 0) {
                total += n;
                if (total > RouseConstants.MAX_CUSTOM_SOUND_BYTES) throw new TooLargeException();
                os.write(buf, 0, n);
            }
        } catch (TooLargeException e) {
            deleteQuietly(out);
            throw new RouseError(RouseError.IO_ERROR, "The file is larger than 20 MB.");
        } catch (IOException | SecurityException e) {
            deleteQuietly(out);
            DiagLog.e("sound", "copy failed", e);
            throw new RouseError(RouseError.IO_ERROR, "Could not read the file.");
        }

        long durationMs;
        try {
            durationMs = probeDurationMs(out);
        } catch (IOException e) {
            deleteQuietly(out);
            throw new RouseError(RouseError.IO_ERROR, "This file can't be played as an alarm sound.");
        }

        String name = displayName == null || displayName.trim().isEmpty() ? "Custom sound" : stripExtension(displayName.trim());
        if (name.length() > 80) name = name.substring(0, 80);
        try {
            JSONObject entry = new JSONObject();
            entry.put("id", id);
            entry.put("name", name);
            entry.put("file", out.getName());
            entry.put("durationMs", durationMs);
            entry.put("addedAt", System.currentTimeMillis());
            if (!store.add(entry)) {
                deleteQuietly(out);
                throw new RouseError(RouseError.IO_ERROR, "Could not save the sound.");
            }
            DiagLog.i("sound", "custom sound added bytes=" + total);
            return customInfo(entry);
        } catch (JSONException e) {
            deleteQuietly(out);
            throw new RouseError(RouseError.IO_ERROR, "Could not save the sound.");
        }
    }

    public void delete(String id) {
        JSONObject removed = store.remove(id);
        if (removed != null) {
            deleteQuietly(new File(soundsDir(), removed.optString("file", "")));
            DiagLog.i("sound", "custom sound deleted");
        }
    }

    /** Decodes the header with MediaPlayer.prepare(); throws IOException if it can't be played. */
    static long probeDurationMs(File f) throws IOException {
        MediaPlayer mp = new MediaPlayer();
        try {
            mp.setDataSource(f.getAbsolutePath());
            mp.prepare();
            return Math.max(-1, mp.getDuration());
        } catch (IllegalStateException | IllegalArgumentException | SecurityException e) {
            throw new IOException("decode failed", e);
        } finally {
            mp.release();
        }
    }

    static String extensionFor(String displayName, String mime) {
        if (displayName != null) {
            int dot = displayName.lastIndexOf('.');
            if (dot >= 0 && dot < displayName.length() - 1) {
                String ext = displayName.substring(dot + 1).toLowerCase(Locale.ROOT);
                if (ext.matches("[a-z0-9]{1,5}")) return ext;
            }
        }
        if (mime != null) {
            String ext = MimeTypeMap.getSingleton().getExtensionFromMimeType(mime);
            if (ext != null && ext.matches("[a-z0-9]{1,5}")) return ext;
        }
        return "audio";
    }

    static String stripExtension(String name) {
        int dot = name.lastIndexOf('.');
        return dot > 0 ? name.substring(0, dot) : name;
    }

    private static void deleteQuietly(File f) {
        if (f != null && f.exists() && !f.delete()) DiagLog.w("sound", "could not delete a sound file");
    }
}
