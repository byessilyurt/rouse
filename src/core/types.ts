/**
 * Rouse domain model — SHARED CONTRACT.
 *
 * Every agent (core, UI, native) codes against these types. Do not change a shape here
 * without flagging it in your report: the Java plugin parses the JSON form of `Alarm`
 * (see RousePlugin.ts), and backups/localStorage persist these shapes verbatim.
 *
 * Rules for this file:
 *  - Types only (plus `as const` literal tables). No runtime logic.
 *  - No enums (they break `node --experimental-strip-types`, used by scripts/).
 *  - Everything must be JSON-serialisable: no Date, Set, Map, undefined-valued keys or class instances.
 *  - All times are epoch milliseconds (UTC instants) unless the name says otherwise
 *    (`hour`/`minute` are local wall-clock fields).
 */

// ─────────────────────────────────────────────────────────────────────────────
// Primitives
// ─────────────────────────────────────────────────────────────────────────────

/** Milliseconds since the Unix epoch (an absolute instant). */
export type EpochMs = number;

/** Opaque alarm id (UUID v4 string from crypto.randomUUID()). */
export type AlarmId = string;

/**
 * Day of week, **0 = Sunday … 6 = Saturday** (same as JS `Date#getDay()`).
 * Java mapping: `java.time.DayOfWeek#getValue() % 7`.
 */
export type Weekday = 0 | 1 | 2 | 3 | 4 | 5 | 6;

// ─────────────────────────────────────────────────────────────────────────────
// Sounds
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Bundled tone ids. Each maps to `res/raw/rouse_<id>.wav` on Android (generated by
 * scripts/gen-sounds.ts from the recipes in defaults.ts) and is synthesised with
 * WebAudio by the web backend. `classic` doubles as the native BACKUP tone.
 */
export type BundledSoundId = 'classic' | 'pulse' | 'siren' | 'chime' | 'buzzer' | 'rise';

/**
 * Reference to the sound an alarm plays.
 *  - bundled: always available, offline.
 *  - custom: a user-picked file that the native side COPIED into device-protected storage
 *    (so it plays before first unlock and survives the original being deleted).
 *    `id` is the native file id returned by `pickCustomSound`; `name` is for display.
 * If a custom sound cannot be played for any reason, native falls back to the backup tone.
 */
export type SoundRef =
  | { kind: 'bundled'; id: BundledSoundId }
  | { kind: 'custom'; id: string; name: string };

// ─────────────────────────────────────────────────────────────────────────────
// Missions
// ─────────────────────────────────────────────────────────────────────────────

/** 1 = trivial … 5 = hard. Exact generator rules live in src/missions/math.ts. */
export type MathDifficulty = 1 | 2 | 3 | 4 | 5;

export interface MathMissionConfig {
  type: 'math';
  difficulty: MathDifficulty;
  /** Problems to solve in a row. 1..20. */
  count: number;
}

export interface MemoryMissionConfig {
  type: 'memory';
  /** Grid is gridSize × gridSize. 3..5. */
  gridSize: 3 | 4 | 5;
  /** Rounds to pass in a row; each round shows a new pattern. 1..5. */
  rounds: number;
}

export interface TypingMissionConfig {
  type: 'typing';
  /** 'random' picks from the bundled phrase list; 'custom' uses customPhrase. */
  phraseMode: 'random' | 'custom';
  /** Used when phraseMode === 'custom'. 1..200 chars after trimming. Kept when switching modes. */
  customPhrase: string;
  /** Case-sensitive comparison. Whitespace/quote/dash normalisation always applies. */
  strictCase: boolean;
  /** Number of phrases to type in 'random' mode (1..5). Ignored in 'custom' mode (always 1). */
  phrases: number;
}

export interface ShakeMissionConfig {
  type: 'shake';
  /** Shakes required. 10..500. */
  count: number;
  /** Detection threshold preset. */
  sensitivity: 'low' | 'medium' | 'high';
}

export interface QrMissionConfig {
  type: 'qr';
  /**
   * The registered code payload, stored after `normalizeCode()` (src/missions/qr.ts).
   * Empty string = not registered yet; an alarm with an unregistered QR mission fails validation.
   * QR is always decodable (BarcodeDetector or jsQR). 1-D barcodes only work where
   * BarcodeDetector exists (Android WebView: yes).
   */
  expectedCode: string;
  /** User's name for where the code lives, e.g. "Bathroom sink". Display only. */
  label: string;
}

export interface TapMissionConfig {
  type: 'tap';
  /** Targets to hit. 5..60. */
  targets: number;
}

export interface StepsMissionConfig {
  type: 'steps';
  /** Steps to walk. 10..500. Detected from accelerometer samples in JS (see D-012). */
  count: number;
}

export interface SquatMissionConfig {
  type: 'squat';
  /** Squats to do. 5..100. Honestly labelled as cheatable (D-007). */
  count: number;
}

/** Discriminated union of every mission's config. Discriminant: `type`. */
export type MissionConfig =
  | MathMissionConfig
  | MemoryMissionConfig
  | TypingMissionConfig
  | ShakeMissionConfig
  | QrMissionConfig
  | TapMissionConfig
  | StepsMissionConfig
  | SquatMissionConfig;

export type MissionType = MissionConfig['type'];

/** Narrow a MissionConfig by its type: `MissionConfigOf<'math'>` = MathMissionConfig. */
export type MissionConfigOf<T extends MissionType> = Extract<MissionConfig, { type: T }>;

/**
 * Missions allowed as the "fallback" (escape-hatch) mission: they need no camera, no sensors,
 * and no setup, so they always work. The fallback must never be easier than the original.
 */
export type FallbackMissionConfig = MathMissionConfig | TypingMissionConfig | MemoryMissionConfig | TapMissionConfig;

/** Device capabilities a mission may need. */
export type MissionRequirement = 'camera' | 'motion';

// ─────────────────────────────────────────────────────────────────────────────
// Alarm
// ─────────────────────────────────────────────────────────────────────────────

export interface SnoozeConfig {
  /** false = no snooze button at all. */
  enabled: boolean;
  /** Minutes until the alarm rings again. 1..60. */
  intervalMin: number;
  /** Snoozes allowed per wake episode. 1..10 (no "unlimited": D-016). */
  maxCount: number;
  /** Snoozing requires completing ONE mission (the first of the plan) first. */
  requireMission: boolean;
}

export interface WakeUpCheckConfig {
  enabled: boolean;
  /** Minutes after dismissal at which "Are you awake?" is shown. 1..30. */
  delayMin: number;
  /** Minutes the user has to confirm before the alarm re-rings. 1..10. */
  windowMin: number;
}

export interface Alarm {
  id: AlarmId;
  /** Local wall-clock hour, 0..23. */
  hour: number;
  /** Local wall-clock minute, 0..59. Alarms fire at second 0. */
  minute: number;
  /**
   * Repeat days, sorted ascending, unique. EMPTY = one-off alarm: rings at the next
   * occurrence of hour:minute and is then disabled (or deleted if deleteAfterRing).
   */
  days: Weekday[];
  enabled: boolean;
  /** Free text, 0..60 chars. Shown on the ring screen and notification. */
  label: string;
  /**
   * "Skip next" marker. Occurrences at instants <= skipUntil are skipped.
   * Set by `skipNext()` to the instant of the occurrence being skipped; null = not skipping.
   * Stale values (in the past) are harmless and are cleared lazily by core. Editing time/days clears it.
   */
  skipUntil: EpochMs | null;
  /** Quick-nap alarms: delete instead of disable after the episode ends. Only meaningful for one-off alarms. */
  deleteAfterRing: boolean;
  sound: SoundRef;
  /** Target alarm-stream volume, percent of STREAM_ALARM max, 10..100. Locked during ringing. */
  volume: number;
  /** Seconds to ramp player gain from ~5% to 100%. 0 = full volume immediately. 0..300. */
  volumeRampSec: number;
  vibrate: boolean;
  snooze: SnoozeConfig;
  /**
   * Missions to complete in order to dismiss (chained). 0..MAX_MISSIONS (3).
   * Empty = plain alarm: dismiss is a single slide/tap (allowed, but the UI recommends a mission).
   */
  missions: MissionConfig[];
  /**
   * Randomise mission TYPES at ring time: each non-QR mission slot is replaced by a random
   * available type with its default config (QR slots are kept as anchors). If `missions` is
   * empty, one random mission is used. Resolved once per ring, by core (RingController).
   */
  randomMission: boolean;
  wakeUpCheck: WakeUpCheckConfig;
  createdAt: EpochMs;
  updatedAt: EpochMs;
}

/** Alarm fields that Settings.alarmDefaults pre-fills into new alarms. */
export type AlarmDefaults = Pick<
  Alarm,
  'sound' | 'volume' | 'volumeRampSec' | 'vibrate' | 'snooze' | 'missions' | 'randomMission' | 'wakeUpCheck'
>;

/** Result of next-fire computation across all alarms. */
export interface NextFire {
  /** The alarm that will ring (lowest createdAt among `alarmIds`, then lowest id). */
  alarmId: AlarmId;
  /** Every enabled alarm due at exactly `fireAt` (merged into one ring, D-014). */
  alarmIds: AlarmId[];
  fireAt: EpochMs;
}

// ─────────────────────────────────────────────────────────────────────────────
// Ringing
// ─────────────────────────────────────────────────────────────────────────────

/** Why a ring started. */
export type RingSource =
  | 'scheduled' //   normal fire
  | 'snooze' //      snooze interval elapsed
  | 'safety' //      re-ring safety alarm found the ring dead (process killed, crash, reboot mid-ring)
  | 'wake-check' //  wake-up check not confirmed in time
  | 'catch-up' //    device was off at fire time, fire time < MISSED_GRACE_MS ago (boot)
  | 'test'; //       "test alarm in N seconds" from the health screen / alarm editor

/**
 * Native-side (authoritative) state of the current wake EPISODE. An episode starts when an
 * alarm first fires and ends on dismissal (no wake check), wake-check confirmation, max
 * wake-check re-rings, or being superseded by another alarm. sessionId is constant across
 * snoozes and re-rings of the same episode.
 */
export type EpisodeState =
  | 'ringing' //            audio playing (or silenced-while-solving); ring UI must be shown
  | 'snoozed' //            waiting for the snooze alarm
  | 'wake-check-wait' //    dismissed; waiting for the wake-up check time
  | 'wake-check-prompt'; // "Are you awake?" shown; deadline running

/** Phase of the JS ring flow (RingController) while the episode is 'ringing'. */
export type RingPhase =
  | 'alerting' //   alarm face: big time, label, [Start mission] [Snooze (n left)]
  | 'solving' //    a mission is on screen
  | 'completing' // all missions done; dismiss call in flight
  | 'snoozed' //    terminal for this controller: snooze accepted
  | 'dismissed' //  terminal: dismiss accepted
  | 'ended'; //     terminal: episode ended externally (superseded, stopped natively)

/** What the mission currently on screen will achieve. */
export type MissionPurpose = 'dismiss' | 'snooze';

/** How a ring was dismissed. */
export type DismissVia = 'mission' | 'fallback' | 'no-mission';

/**
 * JS-side ring session (RingController state). Persisted per sessionId in localStorage so
 * completed missions survive a WebView crash/restart (D-015). Created from an ActiveRing.
 */
export interface RingSession {
  sessionId: string;
  alarmId: AlarmId;
  /** Snapshot of the alarm as mirrored natively when the episode started. */
  alarm: Alarm;
  source: RingSource;
  /** When the episode started (first fire). */
  episodeStartedAt: EpochMs;
  /** When this particular ring (after snooze / re-ring) started. */
  ringStartedAt: EpochMs;
  /** Snoozes used so far in this episode (authoritative copy is native). */
  snoozeCount: number;
  phase: RingPhase;
  /** Non-null only while phase === 'solving'. */
  purpose: MissionPurpose | null;
  /**
   * Resolved mission plan for dismissal (random missions already substituted, unavailable
   * sensor missions already replaced). Fixed for the episode.
   */
  plan: MissionConfig[];
  /** Index into `plan` of the mission being solved / next to solve. */
  missionIndex: number;
  /** Failed attempts on the CURRENT mission (resets when it is passed or replaced). */
  failedAttempts: number;
  /** Failed attempts across the whole episode (statistics). */
  totalFailedAttempts: number;
  /** True while the current mission has been replaced by Settings.fallback.mission. */
  fallbackActive: boolean;
  /** Set when any mission in this episode was completed via the fallback. */
  usedFallback: boolean;
  /** When the current mission was put on screen, null when not solving. */
  missionStartedAt: EpochMs | null;
  /** Sum of time spent in 'solving' (statistics). */
  missionTimeMs: number;
  /** Audio currently muted by the silence-while-solving lease. */
  silenced: boolean;
  /** Last user interaction while solving (drives the idle → un-silence timer). */
  lastActivityAt: EpochMs | null;
}

// ─────────────────────────────────────────────────────────────────────────────
// Settings
// ─────────────────────────────────────────────────────────────────────────────

export interface FallbackSettings {
  /** Offer the fallback mission after this many failed attempts on one mission. 1..10. */
  afterFailures: number;
  /** …or after this many minutes on one mission without passing it. 1..30. */
  afterMinutes: number;
  /** The replacement mission. Never QR/sensor based. */
  mission: FallbackMissionConfig;
}

export interface BedtimeReminderSettings {
  enabled: boolean;
  /**
   * Desired sleep duration in minutes (240..720). The reminder fires at
   * `nextFire.fireAt − sleepGoalMin` if that instant is in the future and the next fire is
   * within 24 h. Computed identically by TS (schedule.ts) and Java.
   */
  sleepGoalMin: number;
}

export interface Settings {
  theme: 'system' | 'light' | 'dark';
  /** 'system' follows the device locale/setting. */
  clockFormat: 'system' | '12h' | '24h';
  /** First column of the day picker. Display only. */
  weekStartsOn: 0 | 1;
  /** Pre-filled into new alarms. */
  alarmDefaults: AlarmDefaults;
  fallback: FallbackSettings;
  /** Idle seconds while solving before the alarm sound resumes. 10..60. */
  silenceWhileSolvingSec: number;
  bedtimeReminder: BedtimeReminderSettings;
  /** Default length for the "Quick nap" button, minutes. 5..120. */
  napMinutes: number;
  /** Onboarding / health walkthrough completed. */
  onboardingDone: boolean;
}

// ─────────────────────────────────────────────────────────────────────────────
// Statistics
// ─────────────────────────────────────────────────────────────────────────────

export type WakeOutcome =
  | 'dismissed' //  completed normally
  | 'missed' //     never rang (device off past grace period, killed by OEM, force-stopped)
  | 'superseded' // another alarm took over the episode
  | 'abandoned'; // episode ended without dismissal for any other reason

export type WakeCheckOutcome = 'off' | 'pending' | 'confirmed' | 'failed';

/** One wake episode, for the local statistics screen. Test rings are never recorded. */
export interface WakeRecord {
  /** = sessionId of the episode. */
  id: string;
  alarmId: AlarmId;
  /** Alarm label at the time (alarm may be deleted later). */
  label: string;
  /** The scheduled instant that started the episode (null if unknown). */
  scheduledFor: EpochMs | null;
  /** First ring start. */
  firstRangAt: EpochMs | null;
  /** Final dismissal, null if not dismissed. */
  dismissedAt: EpochMs | null;
  outcome: WakeOutcome;
  snoozeCount: number;
  missionsCompleted: number;
  missionTimeMs: number;
  failedAttempts: number;
  usedFallback: boolean;
  /** Native fallback math was used because the WebView never became ready. */
  usedNativeFallback: boolean;
  wakeCheck: WakeCheckOutcome;
  /** Times the wake-up check re-rang the alarm. */
  wakeCheckReRings: number;
}

