/** Bookkeeping that is neither alarms nor settings. */
export interface StorageMeta {
  /** Highest AlarmLogEvent.seq already applied to alarms/wakeRecords (see AlarmBackend.getLog). */
  lastAppliedLogSeq: number;
  /** When the state was first created (install-ish). */
  createdAt: EpochMs;
}

/** Whole persisted app state (localStorage key STORAGE_KEY). */
export interface PersistedStateV1 {
  schemaVersion: 1;
  alarms: Alarm[];
  settings: Settings;
  wakeRecords: WakeRecord[];
  meta: StorageMeta;
}

/** Current persisted state shape. Bump with a migration in src/core/storage.ts. */
export type PersistedState = PersistedStateV1;

/**
 * Backup file (JSON export/import, D-001). Custom sounds are NOT included (files stay on the
 * device); on import, custom SoundRefs unknown to this device are replaced by the default
 * bundled sound and reported as warnings.
 */
export interface BackupFileV1 {
  format: 'rouse-backup';
  version: 1;
  exportedAt: EpochMs;
  /** package.json version of the exporting app. Informational. */
  appVersion: string;
  alarms: Alarm[];
  settings: Settings;
  /** Optional on import; always written on export. */
  wakeRecords: WakeRecord[];
}

export type BackupFile = BackupFileV1;

export type ImportMode = 'replace' | 'merge';

export type ImportResult =
  | {
      ok: true;
      alarmsImported: number;
      recordsImported: number;
      /** Human-readable, non-fatal problems (e.g. "Custom sound 'x.mp3' not on this device"). */
      warnings: string[];
    }
  | { ok: false; error: string };

/** Field-level validation problem (alarm editor, import). */
export interface ValidationIssue {
  /** Dotted path, e.g. "missions.1.expectedCode". */
  path: string;
  message: string;
}
